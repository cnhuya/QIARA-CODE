pub fn verify_balance_proof(public_inputs: &[u8], proof_points: &[u8]) -> Result<bool> {
    if proof_points.len() < 256 {
        return err!(crate::QiaraError::InvalidProof);
    }

    let proof_a = &proof_points[0..64];   // Positive A
    let proof_b = &proof_points[64..192];  // Positive B
    let proof_c = &proof_points[192..256]; // Positive C

    // 1. Compute Public Input Multi-Scalar Multiplication (MSM)
    let mut prepared_inputs = [0u8; 64];
    prepared_inputs.copy_from_slice(&IC_POINTS[0]);

    for (i, chunk) in public_inputs.chunks_exact(32).enumerate() {
        if i + 1 >= IC_POINTS.len() {
            break;
        }

        let ic_point = &IC_POINTS[i + 1];

        // Skip point at infinity (0, 0)
        if ic_point.iter().all(|&b| b == 0) {
            continue;
        }

        // Multiply IC[i+1] by scalar
        let mut mul_input = [0u8; 96];
        mul_input[0..64].copy_from_slice(ic_point);
        mul_input[64..96].copy_from_slice(chunk);

        let mut mul_output = [0u8; 64];
        let res = unsafe {
            sol_alt_bn128_group_op(
                ALT_BN128_MUL,
                mul_input.as_ptr(),
                96,
                mul_output.as_mut_ptr(),
            )
        };
        if res != 0 {
            return err!(crate::QiaraError::InvalidProof);
        }

        // Add to running sum
        let mut add_input = [0u8; 128];
        add_input[0..64].copy_from_slice(&prepared_inputs);
        add_input[64..128].copy_from_slice(&mul_output);

        let mut add_output = [0u8; 64];
        let res = unsafe {
            sol_alt_bn128_group_op(
                ALT_BN128_ADD,
                add_input.as_ptr(),
                128,
                add_output.as_mut_ptr(),
            )
        };
        if res != 0 {
            return err!(crate::QiaraError::InvalidProof);
        }

        prepared_inputs = add_output;
    }

    // 2. Perform 4-Pairing Check (Identical to Ethereum verifier.sol assembly):
    // e(A, B) * e(C, -delta) * e(alpha, -beta) * e(L_pub, -gamma) == 1
    let mut pairing_input = [0u8; 768];

    // Pair 1: e(A, B)
    pairing_input[0..64].copy_from_slice(proof_a);
    pairing_input[64..192].copy_from_slice(proof_b);

    // Pair 2: e(C, -delta)
    pairing_input[192..256].copy_from_slice(proof_c);
    pairing_input[256..384].copy_from_slice(&DELTA_NEG_G2);

    // Pair 3: e(alpha, -beta)
    pairing_input[384..448].copy_from_slice(&ALPHA_G1);
    pairing_input[448..576].copy_from_slice(&BETA_NEG_G2);

    // Pair 4: e(L_pub, -gamma)
    pairing_input[576..640].copy_from_slice(&prepared_inputs);
    pairing_input[640..768].copy_from_slice(&GAMMA_NEG_G2);

    let mut pairing_result = [0u8; 32];
    let res = unsafe {
        sol_alt_bn128_group_op(
            ALT_BN128_PAIRING,
            pairing_input.as_ptr(),
            768,
            pairing_result.as_mut_ptr(),
        )
    };

    if res != 0 || pairing_result[31] != 1 {
        return err!(crate::QiaraError::InvalidProof);
    }

    Ok(true)
}

